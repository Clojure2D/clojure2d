# Generate the R oracles of clojure2d.color.whitepoints:
#
# * test/resources/whitepoints/spacesxyz_reference.edn (R spacesXYZ)
#   :adaptation {[method source destination] [9 entries, row major]}: spacesXYZ CAT matrix for
#   clojure2d white points (X, Z read from resources/color/whitepoints.edn), acting on XYZ column
#   vectors.
# * test/resources/whitepoints/colorspec_reference.edn (R colorSpec, independent of colour-science)
#   :d-series {key [X Y Z]} with Y = 1: 1 nm sums with colorSpec's CIE 1931 / 1964 observers
#   (360-830 nm) of D-series spectra linearly interpolated to 1 nm; D65 and D50 are colorSpec's
#   official CIE tables, D55, D60, D75 colorSpec daylightSpectra (CIE basis, M1 M2 rounded) at the
#   nominal CCT (T * 1.4388 / 1.4380).
#
# Run from the repository root:
#
#     Rscript utils/whitepoints/gen_reference.R

suppressPackageStartupMessages(library(spacesXYZ))
suppressPackageStartupMessages(library(colorSpec))

OUT <- "test/resources/whitepoints/spacesxyz_reference.edn"
METHODS <- c("xyz-scaling" = "scaling", "bradford" = "Bradford", "von-kries" = "VonKries",
             "cat02" = "MCAT02", "bianco2010" = "Bianco+Schettini")
PAIRS <- list(c("CIE-2-C", "CIE-2-D65"), c("CIE-2-A", "CIE-2-D50"), c("CIE-2-D65", "CIE-2-E"))

edn <- paste(readLines("resources/color/whitepoints.edn", warn = FALSE), collapse = "")
m <- regmatches(edn, gregexpr(":(\\S+) \\[([^]]+)\\]", edn))[[1]]
wps <- setNames(lapply(sub("^:\\S+ \\[([^]]+)\\]$", "\\1", m),
                       function(s) as.numeric(strsplit(s, " ")[[1]])),
                sub("^:(\\S+) .*$", "\\1", m))
XYZ_w <- function(k) c(wps[[k]][1], 1, wps[[k]][2])

num <- function(x) sprintf("%.17g", x)

rows <- character(0)
for (k in names(METHODS)) {
  for (p in PAIRS) {
    M <- CAT(XYZ_w(p[1]), XYZ_w(p[2]), method = METHODS[[k]])$M
    rows <- c(rows, sprintf("[:%s :%s :%s] [%s]", k, p[1], p[2],
                            paste(num(as.vector(t(M))), collapse = " ")))
  }
}

writeLines(c(sprintf(";; generated by utils/whitepoints/gen_reference.R, spacesXYZ %s",
                     as.character(packageVersion("spacesXYZ"))),
             paste0("{:adaptation\n {", paste(rows, collapse = "\n  "), "}}")), OUT)

# colorSpec D-series

OUT_CS <- "test/resources/whitepoints/colorspec_reference.edn"
OBS <- list("CIE-2" = xyz1931.1nm, "CIE-10" = xyz1964.1nm)
NOMINAL <- c(D55 = 5500, D60 = 6000, D75 = 7500) * 1.4388 / 1.4380

spectrum_of <- function(d) {
  s <- switch(d, D65 = D65.1nm, D50 = D50.5nm,
              daylightSpectra(NOMINAL[[d]], wavelength = seq(300, 830, by = 5), roundMs = TRUE))
  list(w = wavelength(s), v = as.numeric(s))
}

ds <- character(0)
for (d in c("D50", "D55", "D60", "D65", "D75")) {
  sp <- spectrum_of(d)
  for (k in names(OBS)) {
    cmf <- OBS[[k]]
    w <- wavelength(cmf)
    S <- approx(sp$w, sp$v, xout = w)$y
    XYZ <- colSums(S * as.matrix(cmf))
    ds <- c(ds, sprintf(":%s-%s [%s]", k, d, paste(num(XYZ / XYZ[2]), collapse = " ")))
  }
}

writeLines(c(sprintf(";; generated by utils/whitepoints/gen_reference.R, colorSpec %s",
                     as.character(packageVersion("colorSpec"))),
             paste0("{:d-series\n {", paste(ds, collapse = "\n  "), "}}")), OUT_CS)
