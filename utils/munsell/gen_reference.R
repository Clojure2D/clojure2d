# Generate test/resources/munsell/munsellinterpol_reference.edn (oracle: R munsellinterpol, Glenn Davis).
#
# Run from the repository root:
#
#     Rscript utils/munsell/gen_reference.R
#
# Independent of colour-science: value scales in both directions and Bradford C -> D65 sRGB
# at renotation grid points (where munsellinterpol's bilinear interpolation equals colour's exactly).

suppressMessages(library(munsellinterpol))

num <- function(x) ifelse(is.na(x), "##NaN", formatC(x, digits = 17, format = "g"))
vec <- function(xs) paste0("[", paste(num(xs), collapse = " "), "]")
records <- function(m) paste0("[", paste(apply(m, 1, vec), collapse = "\n  "), "]")
strvec <- function(xs) paste0("[", paste0('"', xs, '"', collapse = " "), "]")

V <- round(seq(0, 10, by = 0.1), 10)
scales <- c(astm = "ASTM", newhall = "MGO", osa = "OSA", priest = "PRIEST")

luminance <- sapply(scales, function(w) YfromV(V, which = w))
value_out <- lapply(names(scales), function(k) {
  Y <- luminance[, k]
  Ys <- round(seq(min(Y), max(Y), length.out = 101), 10)
  cbind(Ys, VfromY(Ys, which = scales[[k]]))
})
names(value_out) <- names(scales)

# renotation grid points with integer value, standard hues and even chroma
hues <- c("2.5", "5", "7.5", "10")
letters <- c("R", "YR", "Y", "GY", "G", "BG", "B", "PB", "P", "RP")
grid <- expand.grid(h = hues, l = letters, v = 1:9, c = c(2, 4, 6, 8), stringsAsFactors = FALSE)
spec <- paste0(grid$h, grid$l, " ", grid$v, "/", grid$c)
rgb <- MunsellTosRGB(spec, xyC = "CIE", hcinterp = "bilinear", vinterp = "linear", warn = FALSE)
keep <- !is.na(rgb$OutOfGamut) & !rgb$OutOfGamut
srgb_names <- spec[keep]
srgb <- rgb$RGB[keep, , drop = FALSE]

zero_hue <- c("0P 5/4", "10PB 5/4", "0P 2/2", "10PB 2/2", "0R 6/6", "10RP 6/6")
zx <- MunsellToxyY(zero_hue, xyC = "CIE", hcinterp = "bilinear", vinterp = "linear", warn = FALSE)$xyY

out <- "test/resources/munsell/munsellinterpol_reference.edn"
con <- file(out, "w")
writeLines(";; Oracle values from R munsellinterpol, generated by utils/munsell/gen_reference.R, do not edit.", con)
writeLines(sprintf('{:generated "munsellinterpol %s, R %s"', packageVersion("munsellinterpol"),
                   paste(R.version$major, R.version$minor, sep = ".")), con)
writeLines(paste0(" :luminance {", paste(sprintf(":%s %s", names(scales),
  sapply(names(scales), function(k) records(cbind(V, luminance[, k])))), collapse = "\n  "), "}"), con)
writeLines(paste0(" :munsell-value {", paste(sprintf(":%s %s", names(scales),
  sapply(names(scales), function(k) records(value_out[[k]]))), collapse = "\n  "), "}"), con)
writeLines(paste0(" :srgb-names ", strvec(srgb_names)), con)
writeLines(paste0(" :srgb ", records(srgb)), con)
writeLines(paste0(" :zero-hue-names ", strvec(zero_hue)), con)
writeLines(paste0(" :zero-hue-xyY ", records(zx), "}"), con)
close(con)
cat(sprintf("srgb %d in-gamut grid points -> %s\n", sum(keep), out))
