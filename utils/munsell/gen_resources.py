"""Generate resources/color/munsell_renotation.edn from colour-science.

Run from the repository root:

    /home/ts/penv/.venv/bin/python -I utils/munsell/gen_resources.py

Layout (all arrays flat, row-major):

* hue index  k  = ASTM hue / 2.5 - 1, 0..39 (ASTM hue in (0, 100], see `hue_to_ASTM_hue`)
* value index v = Munsell value - 1, 0..8 (values 1..9)
* chroma index c = chroma / 2 - 1, 0..24 (chromas 2..50)

* :xy          - [x y] pairs at ((k * 9 + v) * 25 + c), NaN when the renotation has no entry
* :max-chroma  - maximum renotation chroma at (k * 9 + v)
* :radial      - 1 when the hue interpolation on the ovoid is radial, 0 when linear,
                 at ((v * 25 + c) * 40 + s), s = ASTM hue segment (s * 2.5, (s + 1) * 2.5)
"""

import math
import sys

import numpy as np
import colour
from colour.notation import MUNSELL_COLOURS_ALL
from colour.notation import munsell as M

HUES, VALUES, CHROMAS, SEGMENTS = 40, 9, 25, 40


def hue_index(hue, code):
    return int(round(M.hue_to_ASTM_hue([hue, code]) / 2.5)) - 1


def segment_spec(s):
    """(hue, code) of the midpoint of ASTM segment s."""
    a = s * 2.5 + 1.25
    decade = math.floor(a / 10)
    code = (7 - decade) % 10
    return a - 10 * decade, 10 if code == 0 else code


def edn_number(x):
    if isinstance(x, float) and math.isnan(x):
        return "##NaN"
    return repr(float(x))


def edn_vector(xs):
    return "[" + " ".join(edn_number(x) for x in xs) + "]"


def main():
    xy = np.full((HUES * VALUES * CHROMAS, 2), np.nan)
    rows = 0
    for (hue_s, value, chroma), (x, y, _Y) in MUNSELL_COLOURS_ALL:
        if value < 1 or value > 9:
            continue
        hue, _, _, code = M.munsell_colour_to_munsell_specification(f"{hue_s} {value}/{chroma}")
        k, v, c = hue_index(hue, code), int(value) - 1, int(chroma) // 2 - 1
        i = (k * VALUES + v) * CHROMAS + c
        assert np.all(np.isnan(xy[i])), f"duplicate entry {hue_s} {value}/{chroma}"
        xy[i] = (x, y)
        rows += 1
    assert rows == int(np.sum(~np.isnan(xy[:, 0]))), "row count mismatch"

    max_chroma = np.zeros(HUES * VALUES)
    for (hue, value, code), chroma in M._munsell_maximum_chromas_from_renotation():
        if 1 <= value <= 9:
            max_chroma[hue_index(hue, code) * VALUES + int(value) - 1] = chroma
    for k in range(HUES):
        for v in range(VALUES):
            cs = [c for c in range(CHROMAS) if not np.isnan(xy[(k * VALUES + v) * CHROMAS + c, 0])]
            assert cs == list(range(len(cs))), "chromas must be contiguous from 2"
            assert max_chroma[k * VALUES + v] == 2 * len(cs), "max chroma mismatch"

    radial = np.zeros(VALUES * CHROMAS * SEGMENTS, dtype=int)
    for v in range(VALUES):
        for c in range(CHROMAS):
            for s in range(SEGMENTS):
                hue, code = segment_spec(s)
                method = M.interpolation_method_from_renotation_ovoid([hue, v + 1, 2 * (c + 1), code])
                radial[(v * CHROMAS + c) * SEGMENTS + s] = 1 if method == "Radial" else 0

    # falsification check: the method is constant inside each open ASTM segment
    rng = np.random.default_rng(20261107)
    for _ in range(20000):
        v, c, s = rng.integers(VALUES), rng.integers(CHROMAS), rng.integers(SEGMENTS)
        a = s * 2.5 + rng.uniform(1e-6, 2.5 - 1e-6)
        decade = math.floor(a / 10)
        code = (7 - decade) % 10
        code = 10 if code == 0 else code
        method = M.interpolation_method_from_renotation_ovoid([a - 10 * decade, v + 1, 2 * (c + 1), code])
        assert (1 if method == "Radial" else 0) == radial[(v * CHROMAS + c) * SEGMENTS + s], (a, v, c)

    out = sys.argv[1] if len(sys.argv) > 1 else "resources/color/munsell_renotation.edn"
    with open(out, "w") as f:
        f.write(
            ";; Munsell Renotation System (all, extrapolated), Illuminant C, CIE 1931 2 degree.\n"
            ";; Generated by utils/munsell/gen_resources.py, do not edit.\n"
        )
        f.write("{:source " + f'"colour-science {colour.__version__}, numpy {np.__version__}; '
                'Munsell Color Science Laboratory, RIT"\n')
        f.write(' :license "BSD-3-Clause. Copyright 2013 Colour Developers; '
                'The Munsell and Kubelka-Munk Toolbox: Copyright 2010-2018 Paul Centore '
                '(Gales Ferry, CT 06335, USA); used by permission."\n')
        f.write(f" :dims {{:hues {HUES} :values {VALUES} :chromas {CHROMAS} :segments {SEGMENTS}}}\n")
        f.write(" :xy " + edn_vector(xy.ravel()) + "\n")
        f.write(" :max-chroma " + edn_vector(max_chroma) + "\n")
        f.write(" :radial [" + " ".join(str(r) for r in radial) + "]}\n")
    print(f"{rows} renotation entries, {int(radial.sum())} radial cells -> {out}")


if __name__ == "__main__":
    main()
