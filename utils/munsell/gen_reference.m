% Generate test/resources/munsell/centore_reference.edn (oracle: Paul Centore's
% Munsell and Kubelka-Munk Toolbox, Sept 2017, GPL-3; not part of this repository).
%
% Run from the repository root, after gen_reference.py, with the unzipped toolbox path:
%
%     octave -q --no-gui --eval "toolbox='/path/to/MunsellAndKubelkaMunkToolboxSept2017'; source('utils/munsell/gen_reference.m')"
%
% Download: https://www.munsellcolorscienceforpainters.com/MunsellAndKubelkaMunkToolbox/MunsellAndKubelkaMunkToolboxSept2017.zip
%
% Inputs are the :xyY-random specs of colour_reference.edn; specs whose chroma exceeds the
% renotation maximum (clamped by clojure2d, rejected by the toolbox) are skipped.

warning('off', 'all');
addpath(genpath(toolbox));

txt = fileread('test/resources/munsell/colour_reference.edn');
block = regexp(txt, ':xyY-random \[(.*?)\]\]', 'tokens', 'once'){1};
spec_rows = regexp(block, '\[([^\[\]]*)', 'tokens');

wanted = 500;
out = zeros(0, 7);
skipped = 0;
for i = 1:numel(spec_rows)
  r = sscanf(spec_rows{i}{1}, '%f')';
  [x y Y Status] = MunsellToxyY(r(1:4));
  if Status.ind == 1
    out(end + 1, :) = [r(1:4) x y Y];
    if size(out, 1) == wanted
      break;
    end
  else
    skipped = skipped + 1;
  end
end

fid = fopen('test/resources/munsell/centore_reference.edn', 'w');
fprintf(fid, ';; Oracle values from Centore''s Munsell and Kubelka-Munk Toolbox (Sept 2017), generated by utils/munsell/gen_reference.m, do not edit.\n');
fprintf(fid, '{:generated "MunsellAndKubelkaMunkToolboxSept2017, Octave %s"\n', OCTAVE_VERSION);
fprintf(fid, ' :skipped %d\n', skipped);
fprintf(fid, ' :xyY [');
for i = 1:size(out, 1)
  fprintf(fid, '[%.17g %.17g %.17g %.17g %.17g %.17g %.17g]', out(i, :));
  if i < size(out, 1)
    fprintf(fid, '\n  ');
  end
end
fprintf(fid, ']}\n');
fclose(fid);
printf('%d specs (%d skipped) -> test/resources/munsell/centore_reference.edn\n', size(out, 1), skipped);
