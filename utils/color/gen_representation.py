"""Generate test/resources/color/representation_reference.edn (oracle for the color representation layer).

Run from the repository root:

    /home/ts/penv/.venv/bin/python -I utils/color/gen_representation.py

Sections:

* :css-names  {name [r g b]}: the 148 CSS Color 4 named colors (matplotlib CSS4_COLORS)
* :hex  [[string r g b a] ...]: hex strings with 3, 4, 6 and 8 digits, with and without #, mixed case,
  parsed by matplotlib to_rgba (0-255)
* :colors  [[r g b] ...]: primaries, secondaries, grays and 500 random colors (numpy default_rng,
  seed 20261113), 0-255
* :hue  hexagonal hue in degrees (Python colorsys.rgb_to_hsv, h * 360)
* :hue-polar  polar hue in degrees: atan2(sqrt(3)/2 (g - b), r - (g + b)/2) mapped to [0, 360)
* :relative-luminance  0-255: colour eotf_sRGB of the channels / 255, weighted with the Y row of the
  sRGB to XYZ matrix used by clojure2d to-XYZ (Lindbloom), times 255
"""

import colorsys
import math

import numpy as np
import matplotlib
import matplotlib.colors as mc
from colour.models import eotf_sRGB

OUT = "test/resources/color/representation_reference.edn"
SRGB_Y = (0.21267285140562248, 0.715152155287818, 0.07217499330655958)  # to-XYZ matrix, Y row


def num(x):
    x = float(x)
    return f"{int(x)}.0" if x == int(x) else repr(x)


def vec(xs):
    return "[" + " ".join(num(x) for x in xs) + "]"


def to255(rgba):
    return [round(v * 255.0) for v in rgba]


def hex_samples():
    rng = np.random.default_rng(20261113)
    out = []
    for _ in range(40):
        r, g, b, a = (int(v) for v in rng.integers(0, 256, 4))
        out.append(f"#{r:02x}{g:02x}{b:02x}")
        out.append(f"{r:02X}{g:02x}{b:02X}")
        out.append(f"#{r:02x}{g:02x}{b:02x}{a:02x}")
        r3, g3, b3 = (int(v) for v in rng.integers(0, 16, 3))
        out.append(f"#{r3:x}{g3:X}{b3:x}")
        a3 = int(rng.integers(0, 16))
        out.append(f"#{r3:x}{g3:x}{b3:X}{a3:x}")
    out += ["#000", "#fff", "#000000", "#ffffff", "#ffffff00", "#00000000", "#12345678"]
    return [[s] + to255(mc.to_rgba(s if s.startswith("#") else "#" + s)) for s in out]


def polar_hue(r, g, b):
    h = math.degrees(math.atan2(math.sqrt(3.0) / 2.0 * (g - b), r - (g + b) / 2.0))
    return h + 360.0 if h < 0.0 else h


def main():
    rng = np.random.default_rng(20261113)
    colors = [[255, 0, 0], [255, 255, 0], [0, 255, 0], [0, 255, 255], [0, 0, 255], [255, 0, 255],
              [0, 0, 0], [128, 128, 128], [255, 255, 255], [255, 128, 0], [10, 200, 30]]
    colors += [list(c) for c in rng.uniform(0.0, 255.0, (500, 3))]
    hue = [colorsys.rgb_to_hsv(r / 255.0, g / 255.0, b / 255.0)[0] * 360.0 for r, g, b in colors]
    hue_polar = [polar_hue(r, g, b) for r, g, b in colors]
    rel_lum = [255.0 * sum(w * float(eotf_sRGB(v / 255.0)) for w, v in zip(SRGB_Y, c)) for c in colors]
    css = {k: to255(mc.to_rgb(v)) for k, v in sorted(mc.CSS4_COLORS.items())}
    out = [f";; generated by utils/color/gen_representation.py, matplotlib {matplotlib.__version__}, numpy {np.__version__}",
           "{:css-names {" + "\n             ".join(f":{k} {vec(v)}" for k, v in css.items()) + "}",
           " :hex [" + "\n       ".join("[" + f'"{h[0]}" ' + " ".join(num(x) for x in h[1:]) + "]" for h in hex_samples()) + "]",
           " :colors [" + " ".join(vec(c) for c in colors) + "]",
           " :hue " + vec(hue),
           " :hue-polar " + vec(hue_polar),
           " :relative-luminance " + vec(rel_lum) + "}"]
    with open(OUT, "w") as f:
        f.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
