"""Generate the limits of the HCL inverse (Sarifuddin and Missaoui 2005; color audit, area B).

Run from the repository root:

    /home/ts/penv/.venv/bin/python -I utils/color/gen_hcl_limits.py

Output: test/resources/color/hcl_limits.edn, the oracle of the private constants of clojure2d.color used by
from-HCL (hcl->max-min).

With r = min / max of the RGB channels and Q = exp(0.03 r) (to-HCL), the ratio C / L depends on r only:

    f(r) = 4 Q (1 - r) / (3 (Q + (Q - 1) r))

f decreases from its maximum at r* to 0 at r = 1 (4/3 at r = 0); no RGB color, even with negative channels, has
C / L above f(r*). Values (mpmath, 40 digits, rounded to the nearest double):

* :r-star - r*, the root of f'(r)
* :k-max - f(r*), the largest C / L reached
* :k2 - -2 / f''(r*), so that r* + sqrt(k2 (k-max - k)) approximates the root of f(r) = k near the maximum
"""

from mpmath import mp, mpf, exp, diff, findroot

OUT = "test/resources/color/hcl_limits.edn"

mp.dps = 40


def f(r):
    q = exp(mpf("0.03") * r)
    return 4 * q * (1 - r) / (3 * (q + (q - 1) * r))


def main():
    r_star = findroot(lambda r: diff(f, r), mpf("-4.5"))
    k_max = f(r_star)
    k2 = -2 / diff(f, r_star, 2)
    with open(OUT, "w") as out:
        out.write(";; generated by utils/color/gen_hcl_limits.py\n")
        out.write(f"{{:r-star {float(r_star)!r}\n :k-max {float(k_max)!r}\n :k2 {float(k2)!r}}}\n")


if __name__ == "__main__":
    main()
